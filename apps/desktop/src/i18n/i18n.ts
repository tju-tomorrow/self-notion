export function createI18n(lang: Lang = storedLang() ?? systemLang()): I18nService {
  const dict = DICT[lang]
  return {
    // 缺词条就把 key 原样吐出来 —— 界面上直接看得见漏了哪个，比静默空串好。
    t(key, vars) {
      const s = dict[key] ?? key
      if (!vars) return s
      return s.replace(/\{(\w+)\}/g, (whole, name: string) => String(vars[name] ?? whole))
    },
  }
}

function storedLang(): Lang | null {
  try {
    const raw = localStorage.getItem('sn.lang')
    return raw === 'zh' || raw === 'en' ? raw : null
  } catch {
    return null
  }
}

function systemLang(): Lang {
  if (typeof navigator === 'undefined') return 'zh'
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}
